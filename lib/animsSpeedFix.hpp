static const int GAnimsSpeedFixCount = sizeof(GAnimsSpeedFixTable)/sizeof(GAnimsSpeedFixTable[0]);

// Devolve a velocidade corrigida para o estado, ou <=0 se nao houver override.
inline float GetAnimsSpeedFix( const char *name )
{
	if( name==NULL || *name==0 ) return 0;
	int lo = 0, hi = GAnimsSpeedFixCount-1;
	while( lo<=hi )
	{
		int mid = (lo+hi)>>1;
		int c = strcmp(GAnimsSpeedFixTable[mid].name, name);
		if( c==0 ) return GAnimsSpeedFixTable[mid].speed;
		if( c<0 ) lo = mid+1; else hi = mid-1;
	}
	return 0;
}

