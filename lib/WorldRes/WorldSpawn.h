//! World spawn matrix container
class WRMatrixContainer
{
private:

//	enf::Array<Object*> m_aLoot;
	enf::Array<WRLoot_Point*> m_aPoint;

	float m_fLeft;
	float m_fTop;
	float m_fRight;
	float m_fBottom;

	int m_iInitialSpawn; ///< Count of items generated by initial spawn
	int m_iCurrentSpawn; ///< Count of items currently spawned

public:

	WRMatrixContainer();
	~WRMatrixContainer();

	//! Add object to resource container
	void OnAddObject( Object* pObject );
	//! Remove object from resource container
	bool OnRemoveObject( Object* pObject );


	//! Insert point
	void InsertPoint( WRLoot_Point* pPoint )
		{ m_aPoint.Insert(pPoint); };

	//! Set initial spawn count
	void SetInitialSpawnCount( int iCount )
		{ m_iInitialSpawn = iCount;	};
	//! Get initial spawn count
	int GetInitialSpawnCount( void ) const
		{ return m_iInitialSpawn;	};

	//! Get current spawn count
	int GetCurrentSpawnCount( void ) const
		{ return m_iCurrentSpawn;	};

//	//! Get count of items in container
//	int GetCount( void ) const
//		{ return m_aLoot.GetCardinality(); };

	//! Get assigned point count
	int GetPointCount( void ) const
		{ return m_aPoint.GetCardinality(); };

	//! Check if population is low
	bool IsPopulationLow( void ) const
		{ return m_iCurrentSpawn<m_iInitialSpawn; };

	//! Set boundings
	void SetBoundings( float fLeft, float fTop, float fRight, float fBottom )
	{
		m_fLeft = fLeft;
		m_fTop = fTop;
		m_fRight = fRight;
		m_fBottom = fBottom;
	};

	float GetLeft( void ) const
		{ return m_fLeft; };
	float GetTop( void ) const
		{ return m_fTop; };
	float GetRight( void ) const
		{ return m_fRight; };
	float GetBottom( void ) const
		{ return m_fBottom; };

	//! Check if pos within coordinates
	bool CheckPos( float fX, float fZ ) const
	{
		return (fX>=m_fLeft)
				&& (fZ>=m_fTop)
				&& (fX<(m_fRight))
				&& (fZ<(m_fBottom));
	};

	//! Find random point
	WRLoot_Point* FindRandomPoint( void );

};


//! World spawn matrix
class WRMatrix
{
private:

	float m_fLeft;
	float m_fTop;
	float m_fWidth;
	float m_fHeight;

	int m_iSizeWidth;
	int m_iSizeHeight;

	enf::Array<WRMatrixContainer*> m_aLoot;

	int m_iInitialSpawn; ///< Count of items generated by initial spawn
	int m_iLowSpawn; ///< Count when replenish start to be functional

	//! Respawn container
	void RespawnAt( WRMatrixContainer* pContainer );

	int m_iLastRespawnCount;

public:

	static const int DEFAULT_MATRIX_SIZE = 16; ///< Initial matrix size

	WRMatrix();
	~WRMatrix();

	//! Add object to resource container
	void OnAddObject( Object* pObject );
	//! Remove object from resource container
	void OnRemoveObject( Object* pObject );

	//! Set boundings
	void SetBoundings( float fLeft, float fTop, float fWidth, float fHeight )
	{
		m_fLeft = fLeft;
		m_fTop = fTop;
		m_fWidth = fWidth;
		m_fHeight = fHeight;
	};

	//! Init matrix
	void Init( int iWidth, int iHeight );
	//! Cleanup
	void Cleanup( void );

	//! Output statistics
	void ListToConsole( void );

	//! When init finished
	void OnInitialized( void );
	//! Update content
	void OnUpdate( void );

	//! Set initial spawn count
	void SetInitialSpawnCount( int iCount )
		{ m_iInitialSpawn = iCount;	};
	//! Set low spawn count
	void SetLowSpawnCount( int iCount )
		{ m_iLowSpawn = iCount;	};

	//! Get initial spawn count
	int GetInitialSpawnCount( void ) const
		{ return m_iInitialSpawn; };
	//! Get initial spawn count
	int GetLowSpawnCount( void )
		{ return m_iLowSpawn; };

	//! Get how many items was respawned during last cycle
	int GetLastRespawnCount( void )
	{
		int c = m_iLastRespawnCount;
		m_iLastRespawnCount = 0;
		return c;
	};

};


